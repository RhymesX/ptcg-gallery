def translate_card_name(chinese_name: str) -> str | None:
    """将中文卡名翻译为英文卡名。

    自动识别并处理卡牌变体后缀（ex, V, GX, VMAX, VSTAR 等）。
    """
    name = chinese_name.strip()
    if not name:
        return None

    # 1) 尝试直接完整匹配
    for mapping in (TRAINER_NAME_MAP, STADIUM_NAME_MAP, TOOL_NAME_MAP, SPECIAL_ENERGY_NAME_MAP, POKEMON_NAME_MAP):
        if name in mapping:
            return mapping[name]

    # 2) 尝试去掉变体后缀后匹配宝可梦名
    suffix, base_name = _extract_variant_suffix(name)
    if base_name in POKEMON_NAME_MAP:
        english_base = POKEMON_NAME_MAP[base_name]
        if suffix:
            return f"{english_base} {suffix}"
        return english_base

    # 3) 尝试模糊匹配 — 对教练卡/物品卡去掉括号内容
    cleaned = _clean_parentheses(name)
    for mapping in (TRAINER_NAME_MAP, STADIUM_NAME_MAP, TOOL_NAME_MAP, SPECIAL_ENERGY_NAME_MAP):
        for cn, en in mapping.items():
            if cleaned.startswith(cn) or name.startswith(cn):
                return en

    return None


def _extract_variant_suffix(name: str) -> tuple[str, str]:
    """从卡名中提取变体后缀和基础名称。"""
    # 常见后缀模式（按长度降序排列避免误匹配）
    suffixes = [
        ("VSTAR", "VSTAR"),
        ("VMAX", "VMAX"),
        ("V-UNION", "V-UNION"),
        ("V", "V"),
        ("GX", "GX"),
        ("ex", "ex"),
        ("EX", "EX"),
        ("BREAK", "BREAK"),
    ]

    for suffix_cn, suffix_en in suffixes:
        if name.endswith(suffix_cn):
            base = name[: -len(suffix_cn)].rstrip("·").rstrip("-").strip()
            if base:
                return (suffix_en, base)

    return ("", name)


def _clean_parentheses(name: str) -> str:
    """去除括号内容，例如 '博士的研究（弗图博士）' → '博士的研究'。"""
    import re

    return re.sub(r"[（(][^)）]*[)）]", "", name).strip()
